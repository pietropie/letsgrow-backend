@compiles(JSONB, "sqlite")
def sqlite_jsonb(element, compiler, **kwargs):
    return "JSON"


class AsyncSessionAdapter:
    """Execute the real SQL generated by routes against an isolated local DB."""
    def __init__(self, session):
        self.session = session

    async def execute(self, statement):
        return self.session.execute(statement)

    def add(self, obj):
        self.session.add(obj)

    async def commit(self):
        self.session.commit()

    async def refresh(self, obj):
        self.session.refresh(obj)

    async def rollback(self):
        self.session.rollback()


class PrivateAccessTests(unittest.TestCase):
    def setUp(self):
        self.engine = create_engine('sqlite://', poolclass=StaticPool, connect_args={'check_same_thread': False})
        Base.metadata.create_all(self.engine, tables=[
            User.__table__, Grow.__table__, Plant.__table__, GrowEvent.__table__, Strain.__table__,
            EnvironmentReading.__table__,
        ])
        self.session = Session(self.engine, expire_on_commit=False)
        self.owner = uuid.uuid4()
        self.other = uuid.uuid4()
        self.grow = uuid.uuid4()
        self.other_grow = uuid.uuid4()
        self.plant = uuid.uuid4()
        self.other_plant = uuid.uuid4()
        for user_id in [self.owner, self.other]:
            self.session.add(User(id=user_id, email=f'{user_id}@example.test', username=str(user_id)))
        self.session.flush()
        for grow_id, user_id in [(self.grow, self.owner), (self.other_grow, self.other)]:
            self.session.add(Grow(id=grow_id, user_id=user_id, name='Ambiente de teste', start_date=date.today()))
        self.session.flush()
        for plant_id, grow_id, user_id in [(self.plant, self.grow, self.owner), (self.other_plant, self.other_grow, self.other)]:
            self.session.add(Plant(id=plant_id, grow_id=grow_id, user_id=user_id, strain_name='Teste'))
        self.session.flush()
        self.own_key = f'{self.owner}/photo.jpg'
        self.other_key = f'{self.other}/photo.jpg'
        self.event = GrowEvent(plant_id=self.plant, event_type='note', event_date=datetime.now(timezone.utc),
                               notes='Minha observação', photo_keys=[self.own_key])
        self.session.add_all([self.event, GrowEvent(plant_id=self.other_plant, event_type='note',
            event_date=datetime.now(timezone.utc), notes='Privado de outra conta', photo_keys=[self.other_key])])
        self.session.commit()
        self.user = SimpleNamespace(id=self.owner, plan='free', plan_expires_at=None, ai_queries_this_month=0)
        app = FastAPI()
        app.include_router(diary.router, prefix='/diary')
        app.include_router(uploads.router, prefix='/uploads')
        app.include_router(plants.router, prefix='/plants')
        app.dependency_overrides[get_current_user] = lambda: self.user
        app.dependency_overrides[get_db] = lambda: AsyncSessionAdapter(self.session)
        self.client = TestClient(app)
        self.sign = self.enterContext(patch('app.api.v1.uploads.presign_download', return_value='https://files.test/own'))
        self.diary_sign = self.enterContext(patch('app.api.v1.diary.presign_download', return_value='https://files.test/own'))
        self.enterContext(patch('app.services.storage.get_minio_presign_client', side_effect=AssertionError('No real object store')))
        self.enterContext(patch('app.api.v1.plants._run_bob_event_hooks', new_callable=AsyncMock))
        self.enterContext(patch('app.services.bob_accountability.run_event_side_effects', new_callable=AsyncMock))

    def tearDown(self):
        self.client.close()
        self.session.close()
        self.engine.dispose()

    def payload(self, key):
        return {'event_type': 'note', 'event_date': '2026-10-16T15:00:00Z', 'notes': 'Teste', 'photo_keys': [key]}

    def test_diary_never_returns_foreign_plant(self):
        for params in [{'plant_id': str(self.other_plant)}, {'grow_id': str(self.other_grow)},
                       {'plant_id': str(self.other_plant), 'grow_id': str(self.grow)}]:
            with self.subTest(params=params):
                response = self.client.get('/diary', params=params)
                self.assertEqual(response.status_code, 200)
                self.assertEqual(response.json(), [])
        self.diary_sign.assert_not_called()

    def test_diary_combines_filters_instead_of_ignoring_grow(self):
        response = self.client.get('/diary', params={'plant_id': str(self.plant), 'grow_id': str(self.other_grow)})
        self.assertEqual(response.json(), [])
        self.diary_sign.assert_not_called()

    def test_own_feed_and_photo_still_work(self):
        for params in [{}, {'plant_id': str(self.plant), 'grow_id': str(self.grow)}]:
            response = self.client.get('/diary', params=params)
            self.assertEqual(response.status_code, 200)
            self.assertEqual([row['plant_id'] for row in response.json()], [str(self.plant)])
            self.assertEqual(response.json()[0]['photo_urls'], ['https://files.test/own'])

    def test_historical_foreign_photo_is_not_signed_or_exposed(self):
        self.event.photo_keys = [self.own_key, self.other_key]
        self.session.commit()
        response = self.client.get('/diary')
        self.assertEqual(response.json()[0]['photo_keys'], [self.own_key])

        response = self.client.get(f'/plants/{self.plant}')
        self.assertEqual(response.status_code, 200)
        self.assertEqual(response.json()['events'][0]['photo_keys'], [self.own_key])
        self.diary_sign.assert_called_once_with('events', self.own_key)
        response = self.client.get(f'/plants/{self.plant}/events')
        self.assertEqual(response.status_code, 200)
        self.assertEqual(response.json()[0]['photo_keys'], [self.own_key])

    def test_private_download_denies_foreign_bucket_and_ambiguous_keys(self):
        for bucket, key in [('events', self.other_key), ('unknown', self.own_key),
                            ('strain-images', self.own_key), ('events', f'{self.owner}/../photo.jpg'),
                            ('events', f'{self.owner}/%2e%2e/photo.jpg'), ('events', f'{self.owner}/'),
                            ('events', f'{self.owner}extra/photo.jpg'), ('events', f'{self.owner}\\photo.jpg'),
                            ('events', f'/{self.own_key}'), ('events', f'{self.owner}/photo.jpg?x=1'),
                            ('avatars', f'avatars/{self.other}/photo.jpg')]:
            with self.subTest(bucket=bucket, key=key):
                response = self.client.get('/uploads/url', params={'bucket': bucket, 'key': key})
                self.assertEqual(response.status_code, 404)
        self.sign.assert_not_called()

    def test_owned_event_and_both_avatar_formats_work(self):
        for bucket, key in [('events', self.own_key), ('avatars', self.own_key), ('avatars', f'avatars/{self.own_key}')]:
            with self.subTest(bucket=bucket, key=key):
                response = self.client.get('/uploads/url', params={'bucket': bucket, 'key': key})
                self.assertEqual(response.status_code, 200)
                self.sign.assert_called_with(bucket, key)

    def test_create_and_bulk_cannot_attach_another_users_photo(self):
        before = self.session.scalar(select(func.count()).select_from(GrowEvent))
        response = self.client.post(f'/plants/{self.plant}/events', json=self.payload(self.other_key))
        self.assertEqual(response.status_code, 404)
        response = self.client.post('/diary', json={**self.payload(self.other_key), 'plant_ids': [str(self.plant)]})
        self.assertEqual(response.status_code, 404)
        self.assertEqual(self.session.scalar(select(func.count()).select_from(GrowEvent)), before)

    def test_update_cannot_attach_another_users_photo(self):
        response = self.client.patch(f'/plants/{self.plant}/events/{self.event.id}', json={'photo_keys': [self.other_key]})
        self.assertEqual(response.status_code, 404)
        self.session.refresh(self.event)
        self.assertEqual(self.event.photo_keys, [self.own_key])

    def test_own_photo_can_be_created_and_cleared(self):
        response = self.client.post(f'/plants/{self.plant}/events', json=self.payload(self.own_key))
        self.assertEqual(response.status_code, 201)
        response = self.client.patch(f'/plants/{self.plant}/events/{self.event.id}', json={'photo_keys': []})
        self.assertEqual(response.status_code, 200)
        self.assertEqual(response.json()['photo_keys'], [])

    def test_bulk_deduplicates_plant_ids(self):
        response = self.client.post('/diary', json={**self.payload(self.own_key), 'plant_ids': [str(self.plant)] * 2,
                                                   'grow_id': str(self.grow)})
        self.assertEqual(response.status_code, 201)
        self.assertEqual(len(response.json()), 1)

    def test_analysis_rejects_historical_foreign_photo_before_ai_import(self):
        self.event.photo_keys = [self.other_key]
        self.session.commit()
        response = self.client.post(f'/plants/{self.plant}/events/{self.event.id}/analyze')
        self.assertEqual(response.status_code, 404)

    def test_period_is_start_inclusive_end_exclusive_and_timezone_aware(self):
        self.event.event_date = datetime(2026, 10, 16, 3, tzinfo=timezone.utc)
        self.session.add_all([
            GrowEvent(plant_id=self.plant, event_type='note', notes='Antes', event_date=datetime(2026, 10, 16, 2, 59, tzinfo=timezone.utc)),
            GrowEvent(plant_id=self.plant, event_type='note', notes='No fim', event_date=datetime(2026, 10, 17, 3, tzinfo=timezone.utc)),
        ])
        self.session.commit()
        response = self.client.get('/diary', params={'start_at': '2026-10-16T00:00:00-03:00', 'end_at': '2026-10-17T00:00:00-03:00'})
        self.assertEqual(response.status_code, 200)
        self.assertEqual([item['id'] for item in response.json()], [str(self.event.id)])

    def test_invalid_periods_are_rejected(self):
        for start, end in [('2026-10-17T00:00:00Z', '2026-10-16T00:00:00Z'),
                           ('2026-10-16T00:00:00', '2026-10-17T00:00:00Z'),
                           ('2026-10-16T00:00:00Z', '2026-10-16T00:00:00Z')]:
            with self.subTest(start=start, end=end):
                self.assertEqual(self.client.get('/diary', params={'start_at': start, 'end_at': end}).status_code, 422)

    def test_archived_history_is_explicit_and_still_private(self):
        self.session.get(Plant, self.plant).is_active = False
        self.session.commit()
        self.assertEqual(self.client.get('/diary').json(), [])
        response = self.client.get('/diary', params={'include_archived': True})
        self.assertEqual([entry['plant_id'] for entry in response.json()], [str(self.plant)])
        self.assertEqual(self.client.get('/diary', params={'include_archived': True, 'plant_id': str(self.other_plant)}).json(), [])

    def test_pagination_does_not_lose_events_with_equal_timestamps(self):
        for _ in range(105):
            self.session.add(GrowEvent(plant_id=self.plant, event_type='note', event_date=self.event.event_date))
        self.session.commit()
        first = self.client.get('/diary', params={'limit': 100, 'offset': 0}).json()
        second = self.client.get('/diary', params={'limit': 100, 'offset': 100}).json()
        ids = [entry['id'] for entry in first + second]
        self.assertEqual(len(ids), 106)
        self.assertEqual(len(set(ids)), 106)


if __name__ == '__main__':
    unittest.main()
